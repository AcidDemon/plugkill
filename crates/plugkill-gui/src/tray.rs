/// What a click in the tray asks the rest of the GUI to do.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TrayEvent {
    /// Left click. The position is the panel's hint for where to open the dashboard.
    Activate {
        x: i32,
        y: i32,
    },
    OpenDashboard,
    OpenSettings,
    Command(Command),
    Quit,
}

pub struct PlugkillTray {
    pub state: TrayState,
    pub status: Option<Status>,
    pub blink_on: bool,
    /// Why the last command did not run, with the moment it was set: the
    /// poller drops it once it is stale, so a one-off failure does not sit
    /// next to a live state that contradicts it. `state` above is still
    /// whatever the daemon reports, so a refused disarm keeps saying armed.
    pub notice: Option<(String, Instant)>,
    /// Where `icons::install` wrote the icon theme; empty when it could not.
    icon_theme_path: String,
    events: async_channel::Sender<TrayEvent>,
}

impl PlugkillTray {
    pub fn new(icon_theme_path: String, events: async_channel::Sender<TrayEvent>) -> Self {
        Self {
            state: TrayState::Down { stalled: false },
            status: None,
            blink_on: false,
            notice: None,
            icon_theme_path,
            events,
        }
    }

    /// Hand an event to the GUI without blocking the menu.
    fn emit(&self, event: TrayEvent) {
        if self.events.try_send(event).is_err() {
            warn!("tray event dropped, the gui side has stopped");
        }
    }
}

impl ksni::Tray for PlugkillTray {
    // Left click goes to `activate` and opens the dashboard; right click shows the menu.
    const MENU_ON_ACTIVATE: bool = false;

    fn id(&self) -> String {
        "plugkill".into()
    }

    fn category(&self) -> Category {
        Category::SystemServices
    }

    fn title(&self) -> String {
        let (title, _) = self.state.title_and_detail(self.status.as_ref());
        format!("plugkill: {title}")
    }

    fn status(&self) -> ksni::Status {
        if self.state.needs_attention() {
            ksni::Status::NeedsAttention
        } else {
            ksni::Status::Active
        }
    }

    fn icon_theme_path(&self) -> String {
        self.icon_theme_path.clone()
    }

    fn icon_name(&self) -> String {
        icons::icon_name(&self.state, self.blink_on).into()
    }

    fn tool_tip(&self) -> ToolTip {
        let (title, detail) = self.state.title_and_detail(self.status.as_ref());
        let mut lines = vec![detail];
        if let Some(s) = &self.status {
            let buses = s.buses();
            let names: Vec<&str> = buses.iter().filter(|b| b.2).map(|b| b.1).collect();
            lines.push(format!(
                "Watching {} of {}: {}",
                names.len(),
                buses.len(),
                names.join(", ")
            ));
            lines.push(format!("Up {}", format_uptime(s.uptime_secs)));
        }
        ToolTip {
            title: format!("plugkill: {title}"),
            description: lines.join("\n"),
            ..Default::default()
        }
    }

    fn activate(&mut self, x: i32, y: i32) {
        self.emit(TrayEvent::Activate { x, y });
    }

    fn menu(&self) -> Vec<MenuItem<Self>> {
        to_ksni(menu::build(
            &self.state,
            self.status.as_ref(),
            self.notice.as_ref().map(|(text, _)| text.as_str()),
        ))
    }
}

