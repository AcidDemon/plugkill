/// An unknown key draws no icon rather than failing the menu; the tests keep
/// the model from producing one.
fn icon_data(key: &str) -> Vec<u8> {
    MENU_ICONS
        .iter()
        .find(|(name, _)| *name == key)
        .map_or_else(Vec::new, |(_, png)| png.to_vec())
}

/// ksni reads a single underscore in a label as an access-key marker.
fn label(text: &str) -> String {
    text.replace('_', "__")
}

fn event_for(action: MenuAction) -> TrayEvent {
    match action {
        MenuAction::OpenDashboard => TrayEvent::OpenDashboard,
        MenuAction::OpenSettings => TrayEvent::OpenSettings,
        MenuAction::Command(command) => TrayEvent::Command(command),
        MenuAction::Quit => TrayEvent::Quit,
    }
}

fn to_ksni(entries: Vec<Entry>) -> Vec<MenuItem<PlugkillTray>> {
    entries
        .into_iter()
        .map(|entry| match entry {
            Entry::Header { text, icon } => StandardItem {
                label: label(&text),
                icon_data: icon_data(icon),
                enabled: false,
                ..Default::default()
            }
            .into(),
            Entry::Info(text) => StandardItem {
                label: label(&text),
                enabled: false,
                ..Default::default()
            }
            .into(),
            Entry::Separator => MenuItem::Separator,
            Entry::Action {
                label: text,
                action,
                icon,
            } => StandardItem {
                label: label(&text),
                icon_data: icon_data(icon),
                activate: Box::new(move |tray: &mut PlugkillTray| tray.emit(event_for(action))),
                ..Default::default()
            }
            .into(),
            Entry::Submenu {
                label: text,
                children,
                icon,
            } => SubMenu {
                label: label(&text),
                icon_data: icon_data(icon),
                submenu: to_ksni(children),
                ..Default::default()
            }
            .into(),
            Entry::Radio {
                options,
                selected,
                icon,
            } => {
                let actions: Vec<MenuAction> = options.iter().map(|(_, a)| *a).collect();
                RadioGroup {
                    selected,
                    select: Box::new(move |tray: &mut PlugkillTray, index| {
                        if let Some(&action) = actions.get(index) {
                            tray.emit(event_for(action));
                        }
                    }),
                    options: options
                        .into_iter()
                        .map(|(text, _)| RadioItem {
                            label: label(&text),
                            icon_data: icon_data(icon),
                            ..Default::default()
                        })
                        .collect(),
                }
                .into()
            }
            Entry::Check {
                label: text,
                checked,
                icon,
            } => CheckmarkItem {
                label: label(&text),
                icon_data: icon_data(icon),
                checked,
                enabled: false,
                ..Default::default()
            }
            .into(),
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_label_escapes_underscores() {
        assert_eq!(label("enp0s31f6_vlan"), "enp0s31f6__vlan");
    }

    #[test]
    fn test_menu_actions_become_tray_events() {
        assert_eq!(
            event_for(MenuAction::OpenDashboard),
            TrayEvent::OpenDashboard
        );
        assert_eq!(event_for(MenuAction::OpenSettings), TrayEvent::OpenSettings);
        assert_eq!(
            event_for(MenuAction::Command(Command::Disarm(60))),
            TrayEvent::Command(Command::Disarm(60))
        );
        assert_eq!(event_for(MenuAction::Quit), TrayEvent::Quit);
    }

    fn icon_keys(entries: &[Entry], out: &mut Vec<&'static str>) {
        for entry in entries {
            match entry {
                Entry::Header { icon, .. }
                | Entry::Action { icon, .. }
                | Entry::Radio { icon, .. }
                | Entry::Check { icon, .. } => out.push(icon),
                Entry::Submenu { icon, children, .. } => {
                    out.push(icon);
                    icon_keys(children, out);
                }
                Entry::Info(_) | Entry::Separator => {}
            }
        }
    }

    #[test]
    fn test_every_menu_icon_key_is_embedded() {
        let watching: Status = serde_json::from_value(serde_json::json!({
            "armed": true, "mode": "enforce", "usb_watching": true, "thunderbolt_watching": true,
            "sdcard_watching": true, "power_watching": true, "network_watching": true,
            "lid_watching": true, "pci_watching": true, "display_watching": true
        }))
        .unwrap();
        // Nothing watched as well, so the unwatched bus icons are covered.
        let idle: Status =
            serde_json::from_value(serde_json::json!({"armed": true, "mode": "learn"})).unwrap();
        let states = [
            TrayState::Down { stalled: false },
            TrayState::Disarmed { secs_left: 60 },
            TrayState::KillPending {
                bus: "power".into(),
                reason: "AC power removed".into(),
                secs_left: 5,
            },
            TrayState::DryRun,
            TrayState::Learning,
            TrayState::Armed,
        ];
        let mut keys = Vec::new();
        for state in &states {
            for status in [&watching, &idle] {
                icon_keys(&menu::build(state, Some(status), None), &mut keys);
            }
        }
        for key in &keys {
            assert!(!icon_data(key).is_empty(), "{key} has no embedded png");
        }
        keys.sort_unstable();
        keys.dedup();
        assert_eq!(keys.len(), MENU_ICONS.len(), "unused icons: {keys:?}");
    }

    #[test]
    fn test_tray_starts_down_and_asks_for_attention() {
        let (tx, _rx) = async_channel::unbounded();
        let tray = PlugkillTray::new(String::new(), tx);
        assert_eq!(tray.state, TrayState::Down { stalled: false });
        assert!(matches!(
            ksni::Tray::status(&tray),
            ksni::Status::NeedsAttention
        ));
        assert_eq!(ksni::Tray::icon_name(&tray), "plugkill-down-symbolic");
    }
}
